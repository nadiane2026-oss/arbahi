const fill = (s, p, l = 0) =>
  s.replace(/\{(\$?)(\w+)\}/g, (_, raw, k) => {
    let v = p?.[k];
    if (Array.isArray(v)) v = v[l]; // قيمة ثنائية اللغة [عربي، English]
    if (v === undefined || v === null) return '';
    return raw ? String(v) : esc(String(v));
  });

/** HTML حسب لغة الواجهة: عربي، أو English، أو الاثنان معاً (عربي فوق، English تحته) */
export function T(key, p) {
  const e = D[key];
  if (!e) return esc(key);
  const ar = fill(e[0], p, 0);
  const en = fill(e[1], p, 1);
  if (prefs.lang === 'ar') return ar;
  if (prefs.lang === 'en') return en;
  const long = e[0].length > 38;
  return `<span class="bi${long ? ' long' : ''}"><span class="a" lang="ar">${ar}</span><span class="e" lang="en" dir="ltr">${en}</span></span>`;
}

