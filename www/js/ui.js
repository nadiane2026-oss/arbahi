export const syncChip = () => `<span class="sync-chip" data-sync data-s="${sync.status}">${T('status.' + sync.status)}</span>`;
export function updateSyncChips() {
  document.querySelectorAll('[data-sync]').forEach((el) => {
    el.dataset.s = sync.status;
    el.innerHTML = T('status.' + sync.status);
    el.title = sync.message || '';
  });
}

