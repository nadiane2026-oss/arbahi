export function wirePrefs() {
  document.addEventListener('click', (e) => {
    const b = e.target.closest?.('[data-pref]');
    if (!b) return;
    if (b.dataset.pref === 'lang') setLang(nextOf(LANGS, prefs.lang)); else setTheme(nextOf(THEMES, prefs.theme));
  });
}

